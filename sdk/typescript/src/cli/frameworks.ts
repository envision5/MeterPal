/**
 * Which framework is this app, and what does its handler look like?
 *
 * The generated handler is the whole point of `meterpal init`: the merchant
 * should not have to work out how to wire a server-side inference call into
 * their app.  Each template keeps the secret key on the server and resolves
 * the end user from the request.
 */

export type Framework =
	| "next"
	| "express"
	| "hono"
	| "fastify"
	| "node";

export type FrameworkDetection = {
	framework: Framework;
	/** The dependency that gave it away. */
	matched: string | null;
	/** Everything that looked like a candidate. */
	candidates: Framework[];
};

const SIGNATURES: Array<{ framework: Framework; deps: string[] }> = [
	{ framework: "next", deps: ["next"] },
	{ framework: "hono", deps: ["hono"] },
	{ framework: "fastify", deps: ["fastify"] },
	{ framework: "express", deps: ["express"] },
];

/**
 * Guess the framework from the app's dependencies.
 *
 * Next.js first: a Next app often also has Express somewhere in its tree,
 * and the Next handler is the one the merchant wants.
 */
export const detectFramework = (
	dependencies: Record<string, string>,
): FrameworkDetection => {
	const candidates: Framework[] = [];
	let matched: string | null = null;

	for (const signature of SIGNATURES) {
		for (const dep of signature.deps) {
			if (dependencies[dep]) {
				candidates.push(signature.framework);
				if (!matched) matched = dep;
				break;
			}
		}
	}

	if (candidates.length === 0) {
		return { framework: "node", matched: null, candidates: [] };
	}

	// SIGNATURES is ordered by specificity, so the first candidate wins.
	return { framework: candidates[0], matched, candidates };
};

/** Where the generated handler goes, per framework. */
export const handlerPath = (framework: Framework): string => {
	switch (framework) {
		case "next":
			return "app/api/chat/route.ts";
		case "express":
			return "src/meterpal-router.ts";
		case "hono":
			return "src/meterpal-router.ts";
		case "fastify":
			return "src/meterpal-router.ts";
		default:
			return "meterpal-handler.ts";
	}
};

