const NEXT_TEMPLATE = `// app/api/chat/route.ts
// Generated by \`npx @meterpal/sdk init\`.
//
// A server-side chat route that bills the end user for what they use.
// The secret key stays on the server; the browser never sees it.

import { createMeterPal, InsufficientBalanceError } from "@meterpal/sdk";

const meterpal = createMeterPal({
	apiKey: process.env.METERPAL_SECRET_KEY!,
	baseURL: process.env.METERPAL_BASE_URL,
});

export async function POST(request: Request) {
	// The end user being billed.  Use your own session id here.
	const userId = request.headers.get("x-user-id") ?? "demo-user";

	const { messages } = (await request.json()) as {
		messages: Array<{ role: "user" | "assistant" | "system"; content: string }>;
	};

	try {
		const completion = await meterpal.chat.completions.create({
			model: process.env.METERPAL_MODEL ?? "custom/demo-gpt",
			messages,
			user: userId,
		});

		return Response.json(completion);
	} catch (error) {
		// The paywall: the end user needs to buy credits.
		if (error instanceof InsufficientBalanceError) {
			const checkout = await error.topUp?.({ returnUrl: "/pricing" });
			return Response.json(
				{
					error: "insufficient_balance",
					message: error.message,
					balance: error.balance,
					requiredCredits: error.requiredCredits,
					checkoutUrl: checkout?.url,
				},
				{ status: 402 },
			);
		}
		throw error;
	}
}
`;

